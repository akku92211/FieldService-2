import org.springframework.security.web.authentication.UsernamePasswordAuthenticationFilter;

@Configuration
public class SecurityConfig {
	
	@Autowired
	private JVMUtil jvmUtil;
	
	@Autowired
	private CustomUserDetailsService customUserDetailsService;
	
	@Bean
	public AuthenticationManager authenticationManager(Authentication config) throws Exception{
		return config.getAuthenticationManager();
		}
	
	@Bean
	public PasswordEncoder  passwordEncoder() {
		return new BCryptPasswordEncoder();
	}
	
	@Bean
	public JvmFilter jvmFilter() {
		return new JvmFilter(customUserDetailsService);
	}
	
	@Bean
	public SecurityFilterChain filterChain(HttpSecurity http) {
		
		http.csrf(csrf-> csrf.disable())
		            .sessionManagement(sm->sm.sessionCreationPolicy(SessionCreationPolicy.STATELESS))
		            .authorizeHttpRequests(auth->auth.requestMatchers("/api/user_auth/**","/api/email_log/**")
		            		.permitAll()
		            		.anyRequest()
		            		.authenticated());
		http.addFilterBefore(jvmFilter(), UsernamePasswordAuthenticationFilter.class);
    	return http.build();
    
	}
}
